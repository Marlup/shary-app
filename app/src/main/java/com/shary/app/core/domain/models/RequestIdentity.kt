package com.shary.app.core.domain.models

import java.nio.charset.StandardCharsets
import java.security.MessageDigest
import java.util.Locale
import java.util.UUID

/**
 * Returns the persisted request ID or a deterministic identity for legacy
 * records created before request IDs were written to the proto store.
 */
fun RequestDomain.stableRequestId(): String {
    val persistedId = id.trim()
    if (persistedId.isNotEmpty()) return persistedId

    return stableLegacyRequestId(
        user = user,
        requesterId = requesterId,
        dateAddedEpochMillis = dateAdded.toEpochMilli(),
        owned = owned,
        recipients = recipients,
        fieldIdentityParts = fields.map { it.key.normalizedIdentityPart() }
    )
}

/** Stable fallback for stored proto records whose ID field predates migration. */
fun stableLegacyRequestId(
    user: String,
    requesterId: String,
    dateAddedEpochMillis: Long,
    owned: Boolean,
    recipients: List<String>,
    fieldIdentityParts: List<String>
): String {
    val canonical = canonicalIdentity(
        "user" to listOf(user.normalizedIdentityPart()),
        "requester" to listOf(requesterId.trim()),
        "date" to listOf(dateAddedEpochMillis.toString()),
        "owned" to listOf(owned.toString()),
        "recipients" to recipients.map(String::normalizedIdentityPart).sorted(),
        "fields" to fieldIdentityParts.map(String::trim).sorted()
    )
    return "legacy-${canonical.sha256Hex()}"
}

/** Creates a route-safe, repeatable ID for a newly imported cloud request. */
fun stableImportedRequestId(
    requesterAddress: String,
    recipientAddress: String,
    fieldKeys: List<String>,
    externalReference: String? = null
): String {
    val canonical = canonicalIdentity(
        "external" to listOf(externalReference.orEmpty().trim()),
        "requester" to listOf(requesterAddress.normalizedIdentityPart()),
        "recipient" to listOf(recipientAddress.normalizedIdentityPart()),
        "fields" to fieldKeys.map(String::normalizedIdentityPart).sorted()
    )
    return "import-${canonical.sha256Hex()}"
}

/** Accepts only canonical UUIDs generated by the sending request workflow. */
fun canonicalCloudRequestId(value: String?): String? = runCatching {
    UUID.fromString(value?.trim().orEmpty()).toString()
}.getOrNull()

private fun canonicalIdentity(vararg sections: Pair<String, List<String>>): String =
    sections.joinToString(separator = "") { (label, values) ->
        buildString {
            append(label.length).append(':').append(label)
            append(values.size).append(':')
            values.forEach { value -> append(value.length).append(':').append(value) }
        }
    }

private fun String.normalizedIdentityPart(): String = trim().lowercase(Locale.ROOT)

private fun String.sha256Hex(): String = MessageDigest
    .getInstance("SHA-256")
    .digest(toByteArray(StandardCharsets.UTF_8))
    .joinToString(separator = "") { byte -> "%02x".format(byte) }
